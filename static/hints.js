  function attachHelp(root) {
    Object.entries(HELP).forEach(([id, text]) => {
      const el = (root || document).querySelector('#' + CSS.escape(id));
      if (!el || el.dataset.help) return;
      el.dataset.help = '1';
      const box = el.closest('.slider-row, .tf, .sw') || el.parentElement;
      const lbl = ['.top label', '.txt > .t-body-m', ':scope > span:first-child'].map(q => box.querySelector(q)).find(Boolean) || box;
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'help-btn'; b.textContent = '?'; b.title = text; b.setAttribute('aria-label', 'Что это: ' + text);
      const pop = document.createElement('p');
      pop.className = 'hint help-pop'; pop.textContent = text; pop.hidden = true;
      b.addEventListener('click', e => { e.preventDefault(); e.stopPropagation(); pop.hidden = !pop.hidden; });
      lbl.appendChild(b);
      // у ползунка подсказка внутри блока (прячется вместе с ним), у полей — сразу после
      // (а в паре полей .two — после пары); CSS «[hidden] + .help-pop» прячет её со скрытым полем
      if (box.classList.contains('slider-row')) box.appendChild(pop);
      else (box.parentElement.classList.contains('two') ? box.parentElement : box).after(pop);
    });
  }

